"""End-to-end supplied-data US3/US4 exercise, never actual research."""
from pathlib import Path
import copy
import json
import sys
sys.path.insert(0,str(Path(__file__).resolve().parents[1]/'tests'))
from test_workflow import WorkflowCase

root=Path(__file__).resolve().parents[1]
t=WorkflowCase()
t.setUp()
checks=[]
def passed(name,detail):checks.append({'name':name,'result':'pass','detail':detail})
try:
    asset,ast=t.ingest()
    cycle=t.cycle(question='Does the supplied generated fixture contain its explicit ILLUSTRATIVE marker?',
        alternatives=['The generated fixture contains the exact ASCII marker','The generated fixture does not contain that marker'],
        necessary_conditions=[{'description':'The generated input must decode as ASCII for this marker test'}],
        predictions=[{'description':'The first alternative predicts at least one exact ILLUSTRATIVE byte sequence'}],
        evidence_needs=['Generated fixture bytes, explicitly known in advance; no blinded discovery'],
        input_assets=[{'id':asset,'revision':ast['revision'],'sha256':ast['sha256']}],
        input_claims=[],expected_output='An illustrative exact byte-marker count and its limited interpretation')
    frozen=copy.deepcopy(cycle['plan'])
    try:t.ds.start_analysis(cycle['id'])
    except t.mod.DossierError as error:
        assert error.exit_code==4
        passed('unprotected_input_blocks_start',error.code)
    else:raise AssertionError('Unprotected input unexpectedly allowed analysis')
    t.result=t.ds.backup(asset)
    t.result=t.ds.start_analysis(cycle['id'])
    current=t.row(cycle['id'])
    assert current['state']=='active' and current['analysis_input_manifest']
    passed('protected_start','Confirmed backup precedes command-owned input manifest and actual analysis start')
    raw=t.original_path(ast).read_bytes()
    raw.decode('ascii')
    count=raw.count(b'ILLUSTRATIVE')
    assert count==1
    t.update('cycles',cycle['id'],{'state':'tested','test_performed':True,
        'method':'Decode generated fixture as ASCII and count exact b\'ILLUSTRATIVE\' byte sequence',
        'result':f'Exact marker count is {count}; known generated text only, no historical claim',
        'limitations':['Fixture contents were supplied and known before the plan; this is capability, not blind discovery']})
    assert t.row(cycle['id'])['plan']==frozen
    passed('performed_fixture_result','Measured one exact marker and retained original frozen predictions')
    hyp=t.row('HYP-0001')
    hyp.update(id='HYP-0008',revision=1,legacy_aliases_json=[],proposition='The supplied fixture contains an explicit ILLUSTRATIVE marker',
        question_scope='This generated byte string only',necessary_conditions_json=[{'description':'ASCII-decodable fixture'}],
        predictions_json=[{'description':'Exact marker count at least one'}],supporting_claim_ids_json=[],contradicting_claim_ids_json=[],dependencies_json=[],
        next_test='Repeat only if the generated input changes',status='supported')
    t.create('hypotheses',hyp)
    passed('scoped_hypothesis','New fixture-only hypothesis is supported without changing seeded alternatives')
    finding=t.finding(cycle['id'])
    assert t.ds.validate()['finding_states'][finding['id']]=='review_pending'
    before=t.row(finding['id'])
    t.review({'kind':'record','id':finding['id'],'revision':1},review_type='finding',
        author_identity='fixture author',reviewer_identity='separate fictional reviewer identity',
        reviewer_instance='Invented review metadata for workflow capability only',
        exposure_rationale='Fixture-only artificial metadata; no actual second factual reviewer is claimed')
    assert t.row(finding['id'])==before
    assert t.ds.validate()['finding_states'][finding['id']]=='shareable_for_selected_reviewers'
    passed('reverse_review_preserves_finding','Fictional reviewer metadata clears structural readiness without editing reviewed finding')
    t.update('cycles',cycle['id'],{'state':'reviewed','finding_ids':[finding['id']],
        'hypothesis_changes':[{'id':'HYP-0008','previous':'untested','current':'supported','reason':'One exact marker in supplied generated bytes'}]})
    t.update('sessions','SES-0001',{'current_milestone':'Illustrative cycle and handoff exercise',
        'current_question':cycle['question'],'findings':[{'id':finding['id'],'revision':1}],
        'completed_task_outputs':[{'task':'supplied US3/US4 exercise','result':'Measured marker, preserved scoped result and fictional review','output_refs':[{'id':finding['id'],'revision':1}]}],
        'gaps':['No actual research evidence; metadata review is fictional'],
        'hypothesis_changes':[{'id':'HYP-0008','reason':'Fixture marker test'}]})
    handoff=t.root/'work/fixture-handoff.md'
    handoff.write_text('# Illustrative handoff\nQuestion: does supplied text contain ILLUSTRATIVE?\nResult: one marker; fixture only.\nNext actions: preserve inputs, keep actual evidence separate, test changed inputs.\n',encoding='utf-8')
    t.result=t.ds.close_session('SES-0001',handoff)
    assert t.ds._closure_complete(t.row('SES-0001'),True)
    passed('exact_final_handoff','Final fixture notes/session snapshot confirmed and mirrored before completion')
    outcome=t.ds.validate('delivery',True)
    assert outcome['_exit_code']==4 and 'actual_dataset_required' in {x['code'] for x in outcome['blockers']}
    passed('illustrative_delivery_rejected','Structurally exercised cycle/report/closure cannot become actual delivery')
    t.update('sources','SRC-0001',{'provenance_limits':'Changed generated source basis requires re-review'})
    assert t.ds.validate()['finding_states'][finding['id']]=='review_pending'
    assert not t.ds._closure_complete(t.row('SES-0001'),True)
    passed('changed_basis_invalidates_readiness','Changed source makes review pending and current snapshot stale')
    result={'exercise':'US3/US4','executed_at':t.mod.utcnow(),'dataset_role':'illustrative','status':'passed','checks':checks,
        'actual_research_written':False,'actual_separate_reviewer_claimed':False,'temporary_dataset_removed':True,
        'frozen_plan':frozen,'observed_marker_count':count,'fixture_delivery_exit_code':outcome['_exit_code']}
finally:t.doCleanups()
(root/'work/us3-us4-exercise.json').write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8')
print(json.dumps(result,indent=2))
